const normalizeArabic = (value: string) => value
  .replace(/ـ/g, '')
  .replace(/[إأآ]/g, 'ا')
  .replace(/ى/g, 'ي')
  .replace(/ؤ/g, 'و')
  .replace(/ئ/g, 'ي')
  .replace(/\s+/g, ' ')
  .trim();

const aliases: Array<[string[], string]> = [
  [['دائرة الموارد البشرية', 'دائره الموارد البشريه'], 'دائرة الموارد البشرية'],
  [['مركز تنمية الموارد البشرية', 'مركز تنميه الموارد البشريه'], 'مركز تنمية الموارد البشرية'],
  [['دائرة سجلات العاملين', 'دائره سجلات العاملين', 'سجلات العاملين'], 'دائرة سجلات العاملين'],
  [['دائرة التنظيم المؤسسي', 'دائره التنظيم الموسسي', 'التنظيم المؤسسي'], 'دائرة التنظيم المؤسسي'],
  [['دائرة التحول الرقمي', 'دائره التحول الرقمي', 'التحول الرقمي'], 'دائرة التحول الرقمي'],
  [['دائرة التدريب والتأهيل', 'دائره التدريب والتاهيل', 'التدريب والتاهيل'], 'دائرة التدريب والتأهيل'],
  [['دائرة البحوث والدراسات', 'دائره البحوث والدراسات', 'البحوث والدراسات'], 'دائرة البحوث والدراسات'],
  [['دائرة الشؤون الإدارية', 'دائره الشوون الاداريه', 'الشؤون الادارية'], 'دائرة الشؤون الإدارية'],
  [['دائرة بناء القدرات', 'دائره بناء القدرات', 'بناء القدرات'], 'دائرة بناء القدرات'],
  [['إدارة البرامج والمشاريع', 'اداره البرامج والمشاريع', 'ادارة البرامج والمشاريع'], 'إدارة البرامج والمشاريع'],
  [['إدارة الدعم التقني', 'اداره الدعم التقني', 'الدعم التقني'], 'إدارة الدعم التقني'],
  [['دائرة الخدمات الإدارية', 'دائره الخدمات الاداريه', 'الخدمات الادارية'], 'دائرة الخدمات الإدارية'],
];

const aliasMap = new Map<string, string>();
aliases.forEach(([variants, canonical]) => variants.forEach((variant) => aliasMap.set(normalizeArabic(variant), canonical)));

export function normalizeDepartmentName(value: string): string {
  const cleaned = value.replace(/\s+/g, ' ').trim();
  if (!cleaned) return 'غير محدد';
  return aliasMap.get(normalizeArabic(cleaned)) ?? cleaned;
}

export function normalizePersonName(value: string): string {
  return value.replace(/\s+/g, ' ').trim();
}
